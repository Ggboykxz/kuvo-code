// The third-party pieces the Windows client is built from, and the rules that keep them
// honest: AI Elements' Shimmer is upstream's file, the packages it needs are named, their
// license terms travel with the app, and the code is linted.
//
//   node --test windows/ai-elements.test.mjs

import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (...parts) => fs.readFileSync(path.join(here, ...parts), "utf8");

const shimmer = read("app", "src", "components", "ai-elements", "shimmer.tsx");
const elementsLicense = read("app", "src", "components", "ai-elements", "LICENSE");
const utils = read("app", "src", "lib", "utils.ts");
const manifest = JSON.parse(read("app", "package.json"));
const lintConfig = JSON.parse(read("app", ".oxlintrc.json"));
const licenses = read("THIRD_PARTY_LICENSES.txt");
const generator = read("tools", "third-party-licenses.mjs");

test("the Shimmer is AI Elements' own file, and says where it came from", () => {
  assert.match(shimmer, /AI Elements — Shimmer \(Vercel\), Apache-2\.0/);
  assert.match(shimmer, /elements\.ai-sdk\.dev\/api\/registry\/shimmer\.json/);
  assert.match(shimmer, /ai-elements 1\.9\.1/);
  // The upstream code, kept as it is published.
  assert.match(shimmer, /bg-\[length:250%_100%,auto\]/);
  assert.match(shimmer, /bg-clip-text text-transparent/);
  assert.match(shimmer, /from "motion\/react"/);
  assert.match(shimmer, /transition=\{\{/);
  assert.match(shimmer, /repeat: Number\.POSITIVE_INFINITY/);
  // And it says which of its parts were changed here.
  assert.match(shimmer, /the import of `cn` points at this app's own/);
});

test("the license of the copied component travels with it", () => {
  assert.match(elementsLicense, /Apache License, Version 2\.0/);
  assert.match(elementsLicense, /Copyright 2023 Vercel, Inc\./);
});

test("the app's own helper is the one the components import", () => {
  assert.match(utils, /from "clsx"/);
  assert.match(utils, /from "tailwind-merge"/);
  assert.match(utils, /export function cn/);
  assert.match(shimmer, /from "\.\.\/\.\.\/lib\/utils"/);
});

test("the packages the components need are named, and pinned by the lockfile", () => {
  for (const name of ["motion", "clsx", "tailwind-merge"]) {
    assert.ok(manifest.dependencies[name], `${name} is a dependency`);
  }
  for (const name of ["tailwindcss", "@tailwindcss/cli", "oxlint"]) {
    assert.ok(manifest.devDependencies[name], `${name} is a build-time dependency`);
  }
  const lock = read("app", "package-lock.json");
  for (const name of ["motion", "clsx", "tailwind-merge", "tailwindcss", "@tailwindcss/cli", "oxlint"]) {
    assert.match(lock, new RegExp(`node_modules/${name.replace("/", "\\/")}"`), `${name} is in the lockfile`);
  }
});

test("every third-party package's terms are listed, and the list is generated", () => {
  for (const name of Object.keys({ ...manifest.dependencies, ...manifest.devDependencies })) {
    assert.match(licenses, new RegExp(`^${name.replace("/", "\\/")} `, "m"), `${name}'s terms are listed`);
  }
  assert.match(licenses, /AI Elements — Shimmer 1\.9\.1/);
  assert.match(licenses, /Apache License, Version 2\.0/);
  // The list is written by a script, and CI checks it.
  assert.match(generator, /--check/);
  assert.match(generator, /process\.exit\(1\)/);
  assert.match(licenses, /generated by windows\/tools\/third-party-licenses\.mjs/);
});

test("the code is linted, and the linter keeps the rules that matter", () => {
  assert.equal(manifest.scripts.lint, "oxlint src");
  assert.equal(manifest.scripts.typecheck, "tsc --noEmit");
  assert.ok(manifest.scripts.check, "the app has one command that lints, type-checks and builds");
  assert.equal(lintConfig.categories.correctness, "error");
  assert.ok(lintConfig.rules["no-unused-vars"], "unused variables are an error");
  assert.ok(lintConfig.rules.eqeqeq, "loose equality is an error");
  assert.ok(lintConfig.rules["react/jsx-key"], "a list without keys is an error");
});
