#!/usr/bin/env node
// Writes windows/THIRD_PARTY_LICENSES.txt: the npm packages the Windows client is built
// from, and the AI Elements component copied into it, with their license terms.
//
//   node windows/tools/third-party-licenses.mjs            (writes the file)
//   node windows/tools/third-party-licenses.mjs --check    (fails if it is out of date)
//
// CI runs the second form after the packages are installed, the way the Mac side's
// scripts/third-party-licenses.sh does.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const windows = path.join(here, "..");
const repo = path.join(windows, "..");
const appDir = path.join(windows, "app");
const out = path.join(windows, "THIRD_PARTY_LICENSES.txt");

const manifest = JSON.parse(fs.readFileSync(path.join(appDir, "package.json"), "utf8"));
const wanted = [
  ...Object.entries(manifest.dependencies ?? {}).map(([name, version]) => ({ name, version, dev: false })),
  ...Object.entries(manifest.devDependencies ?? {}).map(([name, version]) => ({ name, version, dev: true })),
].sort((a, b) => a.name.localeCompare(b.name));

/// The license file a package ships, if it ships one.
const licenseOf = (name) => {
  const dir = path.join(appDir, "node_modules", ...name.split("/"));
  if (!fs.existsSync(dir)) return null;
  const file = fs.readdirSync(dir).find(entry => /^licen[cs]e/i.test(entry) || entry === "COPYING");
  if (!file) return null;
  return { text: fs.readFileSync(path.join(dir, file), "utf8"), file };
};

const header = `THIRD-PARTY LICENSES (Windows client)
===========================================

This file lists the license terms for the third-party code the Windows client is
built from: the npm packages its own package.json names, and the AI Elements
component copied into it. It is generated by windows/tools/third-party-licenses.mjs
and checked in CI. It does not change Kuvo Code's own license.

The Mac app's own third-party terms are in THIRD_PARTY_LICENSES.txt at the root
of the repository, written by scripts/third-party-licenses.sh.
`;

const sections = [];
for (const { name, version, dev } of wanted) {
  const license = licenseOf(name);
  if (!license) {
    console.error(`no license file found for ${name} (is windows/app installed?)`);
    process.exit(1);
  }
  sections.push(
    `\n\n${name} ${version}${dev ? " (build time only)" : ""}\nnpm\n${license.text.trim()}\n`,
  );
}

// The component copied into the app: AI Elements' Shimmer, with its own terms beside it.
const elements = path.join(appDir, "src", "components", "ai-elements");
sections.push(
  `\n\nAI Elements — Shimmer 1.9.1\nhttps://elements.ai-sdk.dev\n` +
    `windows/app/src/components/ai-elements/shimmer.tsx is upstream's file, as published\n` +
    `(ai-elements 1.9.1, registry/default/ai-elements/shimmer.tsx), with the import of its\n` +
    `helper pointed at this app's own. The license travels with it.\n\n` +
    `${fs.readFileSync(path.join(elements, "LICENSE"), "utf8").trim()}\n`,
);

const text = header + sections.join("");
const committed = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";

if (process.argv.includes("--check")) {
  if (committed !== text) {
    console.error("windows/THIRD_PARTY_LICENSES.txt is out of date — run windows/tools/third-party-licenses.mjs and commit it");
    process.exit(1);
  }
  console.log(`ok: ${path.relative(repo, out)} is up to date (${wanted.length} packages)`);
} else {
  fs.writeFileSync(out, text);
  console.log(`ok: ${path.relative(repo, out)} (${wanted.length} packages)`);
}
